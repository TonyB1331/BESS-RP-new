"""Output dataclass for a single simulation step.

Each call to :meth:`~simulation_session.SimulationSession.step` returns a
:class:`StepResult` that bundles together all information produced during the
15-minute slot: trades, a price snapshot, and metadata about the current
simulation position.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional

from ..types import Trade


@dataclass
class StepResult:
    """All outputs produced by a single 15-minute simulation step.

    Attributes
    ----------
    slot:
        The zero-indexed slot number that just completed (0–95).
    day:
        The day counter, starting at 0 and incrementing after every reset.
    time_start:
        Simulation time in minutes at the *start* of the step.
    time_end:
        Simulation time in minutes at the *end* of the step (= ``(slot+1)*15``).
    agent_trades:
        Trades generated by the external agent's orders that were injected
        before the background simulation ran.
    background_trades:
        Trades generated by background agents during the 15-minute window.
    price_snapshot:
        Dictionary with keys ``"bid"``, ``"ask"``, ``"mid"`` — each a list of
        ``Optional[float]`` values, one per product.
    book_depths:
        Dictionary mapping product_id to ``(bid_depth, ask_depth)`` where each
        depth is a ``{price: total_quantity}`` dict.  Only populated for
        products that are still active at the end of the step.
    last_trade_prices:
        Dictionary mapping product_id to the last traded price (or ``None`` if
        no trades have ever occurred for that product).
    active_products:
        List of product ids that are still open for trading at the end of
        the step (i.e. gate closure has not yet been reached).
    is_day_complete:
        ``True`` when this step was the last slot of the day (slot == 95) and
        a :meth:`~simulation_session.SimulationSession.reset` should be called
        before the next :meth:`~simulation_session.SimulationSession.step`.
    """

    slot: int
    day: int
    time_start: float
    time_end: float

    agent_trades: List[Trade] = field(default_factory=list)
    background_trades: List[Trade] = field(default_factory=list)

    price_snapshot: Dict[str, list] = field(default_factory=dict)
    book_depths: Dict[int, tuple] = field(default_factory=dict)
    last_trade_prices: Dict[int, Optional[float]] = field(default_factory=dict)
    active_products: List[int] = field(default_factory=list)

    is_day_complete: bool = False

    # ------------------------------------------------------------------
    # Convenience properties
    # ------------------------------------------------------------------

    @property
    def all_trades(self) -> List[Trade]:
        """Combined list of agent and background trades for this step."""
        return self.agent_trades + self.background_trades

    @property
    def total_volume(self) -> float:
        """Total traded quantity across all trades in this step."""
        return sum(t.quantity for t in self.all_trades)
